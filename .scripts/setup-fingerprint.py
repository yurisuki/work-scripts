#!/usr/bin/env python3
"""Opt-in fingerprint authentication; never install hardware drivers automatically."""
import argparse
import getpass
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

PAM_RULE = 'auth       sufficient   pam_fprintd.so max_tries=1 timeout=10'
PAM_MARKER = '# work-scripts: optional fingerprint login'


def reader_ready(user):
    try:
        import dbus
        bus = dbus.SystemBus()
        manager = dbus.Interface(
            bus.get_object('net.reactivated.Fprint', '/net/reactivated/Fprint/Manager'),
            'net.reactivated.Fprint.Manager',
        )
        for path in manager.GetDevices(timeout=5):
            device = dbus.Interface(bus.get_object('net.reactivated.Fprint', path),
                                    'net.reactivated.Fprint.Device')
            if device.ListEnrolledFingers(user, timeout=5):
                return True
    except Exception as error:
        print(f'Fingerprint unavailable: {error}', file=sys.stderr)
    return False


def configure_lock(enabled):
    target = Path.home() / '.config/hypr/fingerprint.conf'
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink():
        raise RuntimeError(f'Refusing symlink: {target}')
    content = ('# Machine-local; generated by setup-fingerprint.py.\n'
               'auth {\n    fingerprint {\n'
               f'        enabled = {str(enabled).lower()}\n'
               '    }\n}\n')
    target.write_text(content)
    print(f'Hyprlock fingerprint authentication: {"enabled" if enabled else "disabled"}')


def configure_pam(enabled, path=Path('/etc/pam.d/greetd')):
    if path.is_symlink():
        raise RuntimeError(f'Refusing symlink: {path}')
    original = path.read_text()
    managed = PAM_MARKER + '\n' + PAM_RULE + '\n'
    content = original.replace(managed, '')
    if enabled:
        if not Path('/usr/lib/security/pam_fprintd.so').is_file():
            raise RuntimeError('Install the fingerprint PAM module first.')
        if 'pam_fprintd.so' in content:
            raise RuntimeError('Existing unmanaged fingerprint PAM rule; review it manually.')
        lines = content.splitlines(keepends=True)
        candidates = [i for i, line in enumerate(lines)
                      if line.split() == ['auth', 'include', 'system-local-login']]
        if len(candidates) != 1:
            raise RuntimeError('Unrecognized greetd PAM configuration; leaving unchanged.')
        lines.insert(candidates[0], managed)
        content = ''.join(lines)
    if content == original:
        return
    descriptor, backup = tempfile.mkstemp(prefix=path.name + '.backup.', dir=path.parent)
    os.close(descriptor)
    shutil.copy2(path, backup)
    descriptor, staged = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'w') as output:
            output.write(content)
        shutil.copymode(path, staged)
        os.replace(staged, path)
    finally:
        Path(staged).unlink(missing_ok=True)
    print(f'greetd fingerprint login: {"enabled" if enabled else "disabled"}; backup: {backup}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['enable', 'disable', 'auto', 'login', 'disable-login'])
    args = parser.parse_args()
    if args.action == 'disable-login':
        if os.geteuid() != 0:
            subprocess.run(['sudo', sys.executable, str(Path(__file__).resolve()), 'disable-login'], check=True)
        else:
            configure_pam(False)
        return
    if args.action == 'login' and os.geteuid() == 0:
        user = os.environ.get('SUDO_USER')
        if not user or not reader_ready(user):
            raise RuntimeError('Run as your normal user with a working enrolled reader.')
        configure_pam(True)
        return
    if os.geteuid() == 0:
        raise RuntimeError('Run as your normal user, without sudo.')
    if args.action == 'disable':
        configure_lock(False)
        return
    if args.action == 'auto':
        local = Path.home() / '.config/hypr/fingerprint.conf'
        if local.exists() and 'generated by setup-fingerprint.py' in local.read_text():
            print('Preserving local fingerprint preference.')
            return
    if not reader_ready(getpass.getuser()):
        print('No usable enrolled reader. Password authentication is unchanged.')
        if args.action != 'auto':
            sys.exit(1)
        return
    if args.action == 'login':
        subprocess.run(['sudo', sys.executable, str(Path(__file__).resolve()), 'login'], check=True)
    else:
        configure_lock(True)


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
